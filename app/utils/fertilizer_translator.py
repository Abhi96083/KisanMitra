def get_fertilizer_recommendation(key, language='en'):
    """
    Get fertilizer recommendation in specified language
    
    Args:
        key: Recommendation key (NHigh, Nlow, PHigh, Plow, KHigh, Klow)
        language: Language code ('en', 'hi', 'kn')
    
    Returns:
        Recommendation text in specified language, or English if language not found
    """
    if key in fertilizer_recommendations:
        if language in fertilizer_recommendations[key]:
            return fertilizer_recommendations[key][language]
        else:
            # Fallback to English if language not found
            return fertilizer_recommendations[key]['en']
    return "Recommendation not found"
